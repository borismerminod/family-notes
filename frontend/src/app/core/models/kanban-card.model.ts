/**
 * @file kanban-card.model.ts
 * @description Application model for one card of a kanban column.
 *
 * A card is the unit of work the user moves from « À faire » to « Fait »
 * (see .agent/KANBAN/EDITION_CARTES/APPROCHE_KANBAN_EDITION_CARTES.md, D-C2). No wording gap
 * here, unlike the columns: the user reads « carte », the code says `card`, the database says
 * `kanban_cards`.
 *
 * Cards are stored in their own 'kanban_cards' table ('id', 'column_id', 'text', 'note_id',
 * 'position'; see frontend/public/assets/migrations/schema_kanban_cards.sql). The owning column
 * is deliberately not exposed here: a card is always read and written within the context of its
 * column, and carrying the reference twice would invite contradiction — D-L7 taken one level
 * down. No dates either, for the same reason as the columns: nothing displays them, and
 * `kanbans.updated_at` already moves when the cards change (D-K1, D-L6).
 */

import { Note } from './note.model';

export interface KanbanCard {
  /**
   * Unique identifier for the card (UUID). Generated by the edit screen when the card is added,
   * not by the service on insertion (D-C20): the screen has to designate a card — to retype,
   * remove, select or move it — before it exists in the database. It stays stable across saves,
   * and across a move to another column: the upsert sets `column_id` in place rather than
   * recreating the row (D-C10).
   */
  id: string;
  /**
   * What there is to do, in plain text, entered by the user. Required, stored without its leading
   * and trailing spaces, inner spaces being part of it, and falling back to « Sans titre » when
   * nothing is left (D-C30). Plain text only, mono- or multi-line: rich content is the job of the
   * referenced note (H-C10). Two cards may share the same text, their identifiers tell them
   * apart (US2).
   */
  text: string;
  /**
   * The referenced note, or `null` when the card carries no reference — what makes a card more
   * than a sticky note: the board carries the progress of a subject, the note carries its
   * content. The whole {@link Note} is held rather than an identifier and a title, following the
   * precedent of `Note.category` which carries the whole `Category` (D-C3); the screen only uses
   * the title and the identifier, so the read has to hydrate each reference for them.
   *
   * It is `null` in three cases that the screen does not have to tell apart: the card never had a
   * reference, the referenced note was deleted — the card keeps its text and loses only the link,
   * `ON DELETE SET NULL` (H-C6, D-C16) — and the stored `note_id` could not be resolved, which is
   * logged and never brings the board down (D-C15).
   */
  note: Note | null;
  /**
   * Zero-based rank of the card inside its column, top to bottom. It carries the priority the
   * user gave it, so it is persisted rather than derived from the display. Renumbered from the
   * index after every add, removal or move, so the model never holds a stale position (D-C19).
   * Two cards of a same column may momentarily share a position while the board is being saved,
   * which no constraint forbids (D-C8).
   */
  position: number;
}
