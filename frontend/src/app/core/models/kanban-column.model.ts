/**
 * @file kanban-column.model.ts
 * @description Application model for one column of a kanban board.
 *
 * Wording: the user reads « liste », the code and the database say « column »
 * (see .agent/KANBAN/EDITION_LISTES/APPROCHE_KANBAN_EDITION_LISTES.md, D-L5). `kanban-list`
 * already names the screen that lists the boards, so a `KanbanList` model would have meant the
 * exact opposite of what it carries.
 *
 * Columns are stored in their own 'kanban_columns' table ('id', 'kanban_id', 'name', 'position';
 * see frontend/public/assets/migrations/schema_kanban_columns.sql). The owning board is
 * deliberately not exposed here: a column is always read and written within the context of a
 * board, and carrying the reference twice would invite contradiction (D-L7). No dates either —
 * nothing displays them, and `kanbans.updated_at` already moves when the columns change (D-K1).
 */
export interface KanbanColumn {
  /**
   * Unique identifier for the column (UUID). Generated by the edit screen when the column is
   * added, not by the service on insertion (D-L11): the screen has to designate a column before
   * it exists in the database. It stays stable across saves — the upsert strategy updates the row
   * instead of recreating it (D-L10) — which is what the cards of the next batch will attach to.
   */
  id: string;
  /**
   * Column name, entered by the user. Stored without its leading and trailing spaces, inner
   * spaces being part of the name, and falling back to « Sans titre » when nothing is left
   * (D-L17). Two columns of the same board may share the same name, their identifiers tell them
   * apart (D-L6).
   */
  name: string;
  /**
   * Zero-based rank of the column inside its board. It carries the meaning of the workflow, from
   * left to right, so it is persisted rather than derived from the display. Renumbered from the
   * index after every add, removal or move, so the model never holds a stale position (D-L12).
   */
  position: number;
}
