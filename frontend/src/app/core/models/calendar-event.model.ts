/**
 * @file calendar-event.model.ts
 * @description Application model for one event of the calendar.
 *
 * An event belongs to a single civil date, may carry a start and an end time, and may reference
 * one note of the application (see .agent/CALENDAR/EVENT/APPROCHE_CALENDAR_EVENT.md, D-EV10). The
 * event carries the « when », the note carries the « content ».
 *
 * Events are stored in the 'events' table ('id', 'title', 'date', 'start_time', 'end_time',
 * 'note_id'; see frontend/public/assets/migrations/schema_events.sql). The snake_case time fields
 * are kept as the previous calendar batch named them; renaming them is left to a later review.
 */

import { Note } from './note.model';

export interface CalendarEvent {
    /**
     * Unique identifier for the event (UUID). Generated by the event popup when the event is added,
     * not by the service on insertion: the popup has to designate an event before it is saved. It
     * stays stable across saves, and across a move to another date (D-EV16).
     */
    readonly id: string;
    /**
     * What the event is, in plain text, entered by the user and shown in the calendar cell.
     * Required, stored without its leading and trailing spaces. Two events of a same date may share
     * the same text.
     */
    readonly title: string;
    /** The civil date the event belongs to, as `YYYY-MM-DD`, with no time zone attached. */
    readonly date: string;
    /** Start time as `HH:mm`, or `''` when the event has none (`NULL` in the database, D-EV11). */
    readonly start_time: string;
    /**
     * End time as `HH:mm`, or `''` when the event has none (`NULL` in the database, D-EV11). An end
     * time requires a start time, and comes strictly after it.
     */
    readonly end_time: string;
    /**
     * The referenced note, or `null` when the event carries no reference. The whole {@link Note} is
     * held, as `KanbanCard.note` does: the popup shows its title and opens it by its identifier, so
     * the read hydrates each reference.
     *
     * It is `null` in three cases the screen does not tell apart: the event never had a note, the
     * note was deleted — the event stays and loses only the link, `ON DELETE SET NULL` (US10) — or
     * the stored `note_id` could not be resolved, which is logged and never brings the read down.
     */
    readonly note: Note | null;
}
